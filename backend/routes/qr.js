function decodeToken(token) {
  return new Promise((resolve) => {
    jwt.verify(token, process.env.JWTKEY, async (err, decode) => {
      try {
        if (err || !decode?.uid) {
          return resolve({
            success: false,
            data: {},
            message: "Invalid API keys",
          });
        }

        const user = await prisma.user.findFirst({
          where: { uid: String(decode.uid) },
        });

        if (!user || user.is_blocked) {
          return resolve({
            success: false,
            data: {},
            message: "Invalid API keys",
          });
        }

        if (user.api_key !== token) {
          return resolve({
            success: false,
            data: {},
            message: "Token was expired.",
          });
        }

        resolve({
          success: true,
          data: user,
        });
      } catch (dbErr) {
        logger.error("decodeToken error:", dbErr);
        resolve({ success: false, data: {}, message: "Invalid API keys" });
      }
    });
  });
}

// Instance ids are generated by the frontend as `${uid}_${suffix}`.
// Enforce that shape so one tenant can never claim another tenant's session id.
const UNIQUE_ID_SUFFIX = /^[A-Za-z0-9_-]{1,64}$/;
function isValidUniqueIdForUser(uniqueId, uid) {
  if (typeof uniqueId !== "string" || !uid) return false;
  const prefix = `${uid}_`;
  return (
    uniqueId.startsWith(prefix) &&
    UNIQUE_ID_SUFFIX.test(uniqueId.slice(prefix.length))
  );
}

async function findOwnedInstance(uniqueId, uid) {
  if (!uniqueId || !uid) return null;
  return prisma.instance.findFirst({
    where: { uniqueId: String(uniqueId), uid },
  });
}

async function markInstanceInactive(uniqueId) {
  await prisma.instance.updateMany({
    where: { uniqueId },
    data: { status: "INACTIVE" },
  });
}

// QR account limit. `excludeUniqueId` = instance being (re)connected, so re-scanning
// an instance the user already owns does not count it twice. Only one PENDING session
// can exist per user (gen_qr / reconnect cancel the others), so ACTIVE + 1 <= limit holds.
async function checkQrLimit(req, res, excludeUniqueId) {
  const qrLimit = getLimit(req.plan, "qr_accounts");
  if (qrLimit < 1) {
    res.status(403).json(
      buildPlanError(
        "FEATURE_NOT_INCLUDED",
        "qr_accounts",
        0,
        0,
        "Your current plan does not allow WhatsApp QR instances.",
      ),
    );
    return false;
  }

  const currentUsage = await getUsage(req.decode.uid, "qr_accounts", {
    excludeUniqueId,
  });
  if (currentUsage >= qrLimit) {
    res.status(403).json(
      buildPlanError(
        "PLAN_LIMIT_REACHED",
        "qr_accounts",
        currentUsage,
        qrLimit,
        `Your plan allows up to ${qrLimit} WhatsApp instance(s). You currently have ${currentUsage} active instance(s).`,
      ),
    );
    return false;
  }
  return true;
}

function redactToken(params) {
  if (!params || typeof params !== "object") return params;
  const { token, ...rest } = params;
  return { ...rest, token: token ? "[REDACTED]" : undefined };
}

router.post(
  "/gen_qr",
  validateUser,
  checkPlan,
  async (req, res) => {
    try {
      const { title, uniqueId } = req.body;
      if (!title || !uniqueId) {
        return res.json({
          success: false,
          msg: "Please provide the all fields! title is required",
        });
      }

      if (!isValidUniqueIdForUser(uniqueId, req.decode.uid)) {
        return res.status(400).json({
          success: false,
          msg: "Invalid instance id",
        });
      }

      // Never allow an id that already belongs to another tenant
      const foreign = await prisma.instance.findFirst({
        where: { uniqueId, NOT: { uid: req.decode.uid } },
        select: { id: true },
      });
      if (foreign) {
        return res.status(409).json({
          success: false,
          msg: "Instance id already in use",
        });
      }

      if (!(await checkQrLimit(req, res, uniqueId))) return;

      logger.log({ title, uniqueId });

      // Clean up any stale/active pending sessions for this user
      const existingPending = await prisma.instance.findMany({
        where: { uid: req.decode.uid, status: "PENDING" },
        select: { uniqueId: true },
      });
      for (const p of existingPending) {
        if (p.uniqueId !== uniqueId) {
          await cancelPendingSession(p.uniqueId);
        }
      }

      // Check if uniqueId already exists for this user (reconnect existing instance)
      const existing = await findOwnedInstance(uniqueId, req.decode.uid);

      if (existing) {
        await prisma.instance.updateMany({
          where: { uniqueId, uid: req.decode.uid },
          data: { status: "PENDING", qr: null },
        });
        await createSession(
          uniqueId,
          title?.length > 20 ? title.slice(0, 20) : title,
          { isPending: true, isReconnect: true }
        );
      } else {
        await prisma.instance.create({
          data: {
            uid: req.decode.uid,
            title: String(title),
            uniqueId,
            status: "PENDING",
          },
        });
        await createSession(
          uniqueId,
          title?.length > 20 ? title.slice(0, 20) : title,
          { isPending: true, isReconnect: false }
        );
      }

      res.json({
        success: true,
        msg: "Qr code is generating",
      });
    } catch (err) {
      logger.error(err);
      res.json({
        success: false,
        msg: "Something went wrong",
        err: err.message,
      });
    }
  },
);

