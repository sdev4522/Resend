router.post("/cancel_pending", validateUser, async (req, res) => {
  try {
    const { uniqueId } = req.body;
    if (!uniqueId) {
      return res.json({ success: false, msg: "uniqueId is required" });
    }

    // Verify instance ownership
    const inst = await findOwnedInstance(uniqueId, req.decode.uid);

    if (!inst) {
      if (isValidUniqueIdForUser(uniqueId, req.decode.uid)) {
        await cancelPendingSession(uniqueId);
      }
      return res.json({ success: true, msg: "Pending session cancelled" });
    }

    await cancelPendingSession(uniqueId);
    return res.json({ success: true, msg: "Pending session cancelled successfully" });
  } catch (err) {
    logger.error("Error in cancel_pending:", err);
    res.json({ success: false, msg: "Failed to cancel pending session", err: err.message });
  }
});

// reconnect an existing disconnected instance
router.post("/reconnect_instance", validateUser, checkPlan, async (req, res) => {
  try {
    const { uniqueId } = req.body;
    if (!uniqueId) {
      return res.json({ success: false, msg: "uniqueId is required" });
    }

    const inst = await findOwnedInstance(uniqueId, req.decode.uid);

    if (!inst) {
      return res.json({ success: false, msg: "Instance not found" });
    }

    if (!(await checkQrLimit(req, res, uniqueId))) return;

    // Clean up any other pending session for this user first
    const existingPending = await prisma.instance.findMany({
      where: { uid: req.decode.uid, status: "PENDING" },
      select: { uniqueId: true },
    });
    for (const p of existingPending) {
      if (p.uniqueId !== uniqueId) {
        await cancelPendingSession(p.uniqueId);
      }
    }

    await prisma.instance.updateMany({
      where: { uniqueId, uid: req.decode.uid },
      data: { status: "PENDING", qr: null },
    });

    await createSession(
      uniqueId,
      inst.title?.length > 20 ? inst.title.slice(0, 20) : (inst.title || "WhatsApp Web"),
      { isPending: true, isReconnect: true },
    );

    res.json({ success: true, msg: "Reconnection QR generating", data: { uniqueId } });
  } catch (err) {
    logger.error("Error in reconnect_instance:", err);
    res.json({ success: false, msg: "Failed to initiate reconnection", err: err.message });
  }
});

