// ── POST /api/qr/import_wa_contacts  ─────────────────────────────────────────
// Imports fetched WA contacts directly into a phonebook
const MAX_IMPORT_BATCH = 5000;
router.post("/import_wa_contacts", validateUser, checkPlan, async (req, res) => {
  try {
    const { contacts, phonebook_id, phonebook_name } = req.body;
    // contacts: [{ name, mobile }]
    if (!Array.isArray(contacts) || !contacts.length || !phonebook_id)
      return res.json({
        success: false,
        msg: "contacts and phonebook_id required",
      });

    if (contacts.length > MAX_IMPORT_BATCH) {
      return res.status(400).json({
        success: false,
        msg: `You can import at most ${MAX_IMPORT_BATCH} contacts at a time`,
      });
    }

    const phonebookIdNum = parseInt(phonebook_id, 10);
    const phonebook = Number.isInteger(phonebookIdNum)
      ? await prisma.phonebook.findFirst({
          where: { id: phonebookIdNum, uid: req.decode.uid },
          select: { id: true, name: true },
        })
      : null;
    if (!phonebook) {
      return res.status(404).json({ success: false, msg: "Phonebook not found" });
    }

    const rows = contacts
      .filter((c) => c && c.mobile !== undefined && c.mobile !== null && String(c.mobile).trim())
      .map((c) => ({
        uid: req.decode.uid,
        phonebook_id: String(phonebook.id),
        phonebook_name: phonebook_name || phonebook.name || "",
        name: c.name ? String(c.name) : "",
        mobile: String(c.mobile).trim(),
      }));

    if (!rows.length) {
      return res.json({ success: false, msg: "No valid contacts to import" });
    }

    // Contact limit applies to the whole batch, not just the first row
    const contactLimit = getLimit(req.plan, "contacts");
    const currentUsage = await getUsage(req.decode.uid, "contacts");
    if (currentUsage + rows.length > contactLimit) {
      return res.status(403).json(
        buildPlanError(
          "PLAN_LIMIT_REACHED",
          "contacts",
          currentUsage,
          contactLimit,
          `Your plan allows up to ${contactLimit.toLocaleString()} contacts. You have ${currentUsage} and tried to import ${rows.length}. Please delete some contacts or upgrade your plan.`,
        ),
      );
    }

    const result = await prisma.contact.createMany({ data: rows });

    res.json({ success: true, inserted: result.count });
  } catch (err) {
    logger.error(err);
    res.json({ success: false, msg: "Something went wrong" });
  }
});

